'use strict';
// Every release carries SHA256SUMS (owner 2026-11-14, 「넣기」 for 1.2.13): one `sha256sum` line per uploaded installer
// file, from the digests npm run dist verified, so a user can check the download (`certutil -hashfile … SHA256`).
// No network: GitHub is a recorded fake, the files live in a temporary folder.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const { publishRelease, sha256Sums, releaseAssets } = require('../scripts/release.cjs');

const sha = text => crypto.createHash('sha256').update(text).digest('hex');
const A = 'ca978112ca1bbdcafac231b39a23dc4da786eff8147c4e72b9807785afee48bb'; // sha256 of 'a'

test('SHA256SUMS is the sha256sum format: 64 hex, two spaces, the name, sorted by name, LF, ASCII, a final newline', () => {
  assert.equal(sha('a'), A);
  const text = sha256Sums([
    { name: 'latest.yml', sha256: sha('c') },
    { name: 'Dayboard-1.2.13.exe.blockmap', sha256: sha('b') },
    { name: 'Dayboard-1.2.13.exe', sha256: A },
  ]);
  assert.equal(text, `${A}  Dayboard-1.2.13.exe\n${sha('b')}  Dayboard-1.2.13.exe.blockmap\n${sha('c')}  latest.yml\n`);
  assert.equal(/\r/.test(text), false, 'LF only');
  assert.equal(/^[\x00-\x7f]*$/.test(text), true, 'ASCII only');
  for (const line of text.trimEnd().split('\n')) assert.match(line, /^[0-9a-f]{64} {2}[A-Za-z0-9._-]+$/);
  // Nothing that could break a line or the format gets in.
  assert.throws(() => sha256Sums([{ name: 'a\nb', sha256: A }]), /name/);
  assert.throws(() => sha256Sums([{ name: '설치.exe', sha256: A }]), /name/);
  assert.throws(() => sha256Sums([{ name: 'x.exe', sha256: A.toUpperCase() }]), /sha256/);
  assert.throws(() => sha256Sums([{ name: 'x.exe', sha256: A.slice(1) }]), /sha256/);
});

test('releaseAssets checks the verified digests, writes SHA256SUMS next to the installer from those digests and lists it with the three files', t => {
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'dayboard-sums-'));
  t.after(() => fs.rmSync(out, { recursive: true, force: true }));
  const files = { 'Dayboard-9.9.9.exe': 'a', 'Dayboard-9.9.9.exe.blockmap': 'b', 'latest.yml': 'c' };
  for (const [name, text] of Object.entries(files)) fs.writeFileSync(path.join(out, name), text);
  const outputs = {
    installer: { file: 'Dayboard-9.9.9.exe', sha256: sha('a'), size: 1 },
    blockmap: { file: 'Dayboard-9.9.9.exe.blockmap', sha256: sha('b') },
    latest: { file: 'latest.yml', sha256: sha('c') },
  };
  const { assets, sums } = releaseAssets(out, outputs);
  assert.deepEqual(assets.map(file => path.basename(file)), ['Dayboard-9.9.9.exe', 'Dayboard-9.9.9.exe.blockmap', 'latest.yml', 'SHA256SUMS']);
  assert.equal(path.dirname(assets[3]), out, 'next to the installer');
  assert.equal(sums, `${sha('a')}  Dayboard-9.9.9.exe\n${sha('b')}  Dayboard-9.9.9.exe.blockmap\n${sha('c')}  latest.yml\n`);
  assert.equal(fs.readFileSync(assets[3], 'latin1'), sums, 'the written file is the text, byte for byte');
  // A file changed after npm run dist is refused before anything is written or uploaded.
  fs.rmSync(assets[3]);
  fs.writeFileSync(path.join(out, 'latest.yml'), 'changed');
  assert.throws(() => releaseAssets(out, outputs), /latest\.yml changed since npm run dist verified it/);
  assert.equal(fs.existsSync(path.join(out, 'SHA256SUMS')), false);
});

function recordingGitHub() {
  const uploads = [];
  let release = null;
  const call = async (method, url, body, headers = {}) => {
    if (method === 'GET') { const e = new Error('404'); e.status = 404; throw e; }
    if (method === 'POST' && url.endsWith('/releases')) { release = { id: 7, draft: true, assets: [], upload_url: 'https://uploads.example/releases/7/assets{?name,label}', ...JSON.parse(body) }; return release; }
    if (method === 'POST') { const name = new URL(url).searchParams.get('name'); uploads.push({ name, type: headers['Content-Type'], body: Buffer.from(body) }); release.assets.push({ id: release.assets.length + 100, name }); return {}; }
    if (method === 'PATCH') { release = { ...release, ...JSON.parse(body) }; return { ...release, html_url: 'https://example/r/7' }; }
    throw new Error(`unexpected ${method} ${url}`);
  };
  return { call, uploads };
}

test('publishRelease uploads SHA256SUMS as text/plain with exactly the generated bytes; the other types stay', async () => {
  const sums = sha256Sums([{ name: 'Setup.exe', sha256: A }, { name: 'latest.yml', sha256: sha('c') }]);
  const gh = recordingGitHub();
  const read = file => path.basename(file) === 'SHA256SUMS' ? Buffer.from(sums, 'latin1') : Buffer.from('bytes');
  await publishRelease({ call: gh.call, api: 'https://api.example/repos/o/r', tag: 'v9.9.9', version: '9.9.9', notes: 'notes', branch: 'main',
    assets: ['/x/Setup.exe', '/x/Setup.exe.blockmap', '/x/latest.yml', '/x/SHA256SUMS'], read, log: () => {} });
  const byName = Object.fromEntries(gh.uploads.map(u => [u.name, u]));
  assert.equal(byName.SHA256SUMS.type, 'text/plain');
  assert.equal(byName.SHA256SUMS.body.equals(Buffer.from(sums, 'latin1')), true);
  assert.equal(byName['latest.yml'].type, 'text/yaml');
  assert.equal(byName['Setup.exe'].type, 'application/octet-stream');
  assert.equal(byName['Setup.exe.blockmap'].type, 'application/octet-stream');
});

test('npm run release builds its file list with releaseAssets, so the record and --dry carry SHA256SUMS', () => {
  const source = fs.readFileSync(path.join(__dirname, '..', 'scripts', 'release.cjs'), 'utf8');
  const main = source.slice(source.indexOf('if (require.main === module)'));
  assert.match(main, /const \{ assets, sums \} = releaseAssets\(at\(pkg\.build\.directories\.output\), check\.outputs\);/);
  assert.match(main, /if \(args\.has\('--dry'\)\) \{[^\n]*sha256sums: sums\.trimEnd\(\)\.split\('\\n'\)/);
  assert.match(main, /publishRelease\(\{[^\n]*assets \}\)/);
  assert.match(main, /const record = \{ version, tag, url: published\.html_url, assets: assets\.map\(file => path\.basename\(file\)\),/);
  // The old inline list of three is gone (it would upload without SHA256SUMS).
  assert.equal(main.includes('[check.outputs.installer, check.outputs.blockmap, check.outputs.latest].map('), false);
});
